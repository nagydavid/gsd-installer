#!/usr/bin/env bash
# tools/bundle.sh — generate dist/install.sh: a self-contained single-file
# installer (no clone, no bootstrap). Run after editing any source file:
#   tools/bundle.sh && git add dist/install.sh
#
# The modular sources (install.sh, lib/, profiles/, data/) are embedded as a
# base64 tarball; the generated script extracts them to a temp dir and runs.
set -euo pipefail
cd "$(cd "$(dirname "$0")/.." && pwd)"

command -v node >/dev/null 2>&1 || { echo "bundle needs node for a sources sanity check" >&2; }

mkdir -p dist
PAYLOAD="$(tar cz -f - install.sh lib profiles data | base64 | tr -d '\n')"
OUT="dist/install.sh"

{
  cat <<'HEADER'
#!/usr/bin/env bash
# GSD Core Installer — self-contained single file (no clone, no bootstrap).
#
#   curl -fsSL https://raw.githubusercontent.com/nagydavid/gsd-installer/main/dist/install.sh | bash
#   curl -fsSL .../dist/install.sh | bash -s -- --harness both --dry-run
#   GSD flags: --harness opencode|copilot|both  --dry-run  --rollback
#              --profile economy|balanced|quality|custom  --recommend-models  --yes
#
# GENERATED by tools/bundle.sh from the modular sources in this repository.
# Edit the sources and regenerate — do not edit this file.
set -euo pipefail

TMP="$(mktemp -d "${TMPDIR:-/tmp}/gsd-installer.XXXXXX" 2>/dev/null || mktemp -d)"
trap 'rm -rf "$TMP"' EXIT INT TERM

decode() { base64 -d 2>/dev/null || base64 --decode 2>/dev/null || base64 -D; }

PAYLOAD='
HEADER
  printf '%s\n' "$PAYLOAD"
  cat <<'FOOTER'
'

printf '%s' "$PAYLOAD" | decode | tar xz -C "$TMP"
"$TMP/install.sh" "$@"
FOOTER
} > "$OUT"
chmod +x "$OUT"
bash -n "$OUT"
echo "wrote $OUT ($(wc -c < "$OUT") bytes)"
